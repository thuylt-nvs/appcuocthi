// Backward compatibility helper for legacy code accessing competencyId
(function attachCompetencyId(obj) {
  if (Array.isArray(obj)) {
    obj.forEach(q => {
      if (q && q.primaryCompetencyId) {
        q.competencyId = q.primaryCompetencyId;
      }
    });
  } else if (typeof obj === 'object' && obj !== null) {
    Object.values(obj).forEach(val => attachCompetencyId(val));
  }
})(ChampionshipQuestions);

